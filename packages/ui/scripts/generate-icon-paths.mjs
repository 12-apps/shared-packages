// `src/icons/paths.generated.ts` is GENERATED from `src/icons/glyphs.json`. This writes it.
//
// The web components draw their glyphs with `@mui/icons-material`, which is an
// SVG path per icon behind MUI's `SvgIcon`. A native component cannot import
// that module (it renders a DOM `<svg>` through emotion), but it CAN draw the
// same path through `react-native-svg` — and "the same path" is the only way a
// native close button is the web close button rather than a look-alike from a
// different icon set.
//
// So the path data is read out of the installed `@mui/icons-material` and
// written here as plain strings. `glyphs.json` is the list of icons the ported
// components use; `paths.generated.ts` is what both renderers read. Adding an
// icon is one line in the list and a re-run; `--check` fails CI if the two have
// drifted, which is what happens when someone edits the generated file by hand
// or bumps `@mui/icons-material` to a release that redrew a glyph.
//
// Usage:
//   node scripts/generate-icon-paths.mjs           # write src/icons/paths.generated.ts
//   node scripts/generate-icon-paths.mjs --check   # fail if it has drifted (CI)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GLYPHS = join(PACKAGE_ROOT, 'src/icons/glyphs.json');
const OUTPUT = join(PACKAGE_ROOT, 'src/icons/paths.generated.ts');

const check = process.argv.includes('--check');
const require = createRequire(join(PACKAGE_ROOT, 'package.json'));

/** @type {string[]} */
const names = JSON.parse(readFileSync(GLYPHS, 'utf8'));

/**
 * The icon module is CJS that calls `createSvgIcon(<path d="…"/>, 'Name')`.
 * Loading it would need React and JSX runtime; reading the `d` attribute out
 * of the source is enough and keeps this script dependency-free. Icons with
 * several paths (a few outlined variants) are captured as every `d` in order.
 */
function pathsFor(name) {
  const file = require.resolve(`@mui/icons-material/${name}`);
  const source = readFileSync(file, 'utf8');
  const paths = [...source.matchAll(/\bd:\s*"([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) {
    throw new Error(`generate-icon-paths: no <path d> found in ${file}`);
  }
  return paths;
}

const entries = [...names]
  .sort((a, b) => a.localeCompare(b))
  .map((name) => `  ${name}: ${JSON.stringify(pathsFor(name))},`)
  .join('\n');

const expected = `// GENERATED by scripts/generate-icon-paths.mjs from src/icons/glyphs.json.
// Do not edit: run \`pnpm icons:generate\`; \`pnpm icons:check\` fails CI on drift.
//
// Each entry is the \`d\` of every <path> in the matching @mui/icons-material
// module, in a 24x24 viewBox — the SAME geometry the web renders through
// SvgIcon, so the native Icon draws the identical glyph.

/** Path data per glyph, in a 0 0 24 24 viewBox. */
export const ICON_PATHS = {
${entries}
} as const;

export type IconName = keyof typeof ICON_PATHS;

export const ICON_NAMES = Object.keys(ICON_PATHS) as readonly IconName[];
`;

if (check) {
  const actual = readFileSync(OUTPUT, 'utf8');
  if (actual !== expected) {
    console.error(
      'ui icons: DRIFT — src/icons/paths.generated.ts does not match glyphs.json and the installed @mui/icons-material.\n' +
        'Run "pnpm icons:generate" and commit the result.',
    );
    process.exit(1);
  }
  console.log(`ui icons: ${names.length} glyphs in sync.`);
} else {
  writeFileSync(OUTPUT, expected);
  console.log(`ui icons: wrote ${names.length} glyphs to src/icons/paths.generated.ts`);
}
